function buildBody(name, tmpl) {
  const ctrls = CONTROLS[name];
  if (!ctrls || !ctrls.length) return tmpl;
  const lines = ctrls.map(c => `  ${c}`).join('\n');
  return `--[[\n  Controls:\n${lines}\n]]\n${tmpl}`;
}

function buildEntry(item, category) {
  const tag = CAT_LABEL[item.cat] || item.cat;
  return {
    id: crypto.randomUUID(),
    title: item.name,
    category,
    tags: [tag],
    body: buildBody(item.name, item.tmpl),
    author: AUTHOR,
    likes: [],
    createdAt: new Date().toISOString()
  };
}

